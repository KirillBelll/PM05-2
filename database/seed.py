def apply_schema():
    url = make_url(Config.SQLALCHEMY_DATABASE_URI)
    conn = pymysql.connect(host=url.host or "localhost", port=url.port or 3306,
                           user=url.username or "root", password=url.password or "",
                           charset="utf8mb4", autocommit=True)
    with open(os.path.join(ROOT, "database", "schema.sql"), encoding="utf-8") as fh:
        sql = fh.read()
    statements = []
    for chunk in sql.split(";"):
        lines = [l for l in chunk.splitlines() if not l.strip().startswith("--")]
        stmt = "\n".join(lines).strip()
        if stmt:
            statements.append(stmt)
    with conn.cursor() as cur:
        for stmt in statements:
            cur.execute(stmt)
    conn.close()
    print(f"Схема применена: {len(statements)} SQL-операторов")


